/* Run with Node after starting the static preview server on port 8003.
   Reuses the review browser tools already installed in the local temp directory. */
const path = require('path');
const fs = require('fs');
const { chromium } = require(path.join(require('os').tmpdir(), 'vendeze-ui-qa', 'node_modules', 'playwright'));
const axePath = require.resolve(path.join(require('os').tmpdir(), 'vendeze-ui-qa', 'node_modules', 'axe-core'));
const output = __dirname;
const checks = [];
const errors = [];
const failedAssets = [];
const apiRequests = [];
const accessibility = [];
const base = 'http://127.0.0.1:8003/?preview=1';
const assert = (value, label) => { if (!value) throw new Error(label); checks.push(label); };

async function main() {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    const page = await context.newPage();
    page.setDefaultTimeout(8000);
    page.setDefaultNavigationTimeout(12000);
    page.on('pageerror', e => errors.push(e.message));
    page.on('response', r => { if (r.status() >= 400 && r.url().startsWith('http://127.0.0.1:8003')) failedAssets.push(r.url()); });
    page.on('request', r => { if (r.url().includes('localhost:8080')) apiRequests.push(r.url()); });
    await page.addInitScript(() => localStorage.setItem('vendeze-state-v2', 'production-storage-untouched'));
    const home = async () => {
      await page.evaluate(() => { location.hash = '#/'; });
      await page.locator('.celebrate-home').waitFor();
    };
    const assets = async () => {
      await page.evaluate(async () => {
        for (const image of document.querySelectorAll('img[loading="lazy"]')) image.loading = 'eager';
        await Promise.all([...document.images].map(image => image.decode().catch(() => {})));
        await document.fonts.ready;
      });
    };
    const scan = async label => {
      await page.addScriptTag({ path: axePath });
      const result = await page.evaluate(() => axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa'] } }));
      accessibility.push({ label, violations: result.violations.map(v => ({ id: v.id, impact: v.impact, description: v.description, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) })) });
      assert(!result.violations.length, label + ' accessibility scan passes');
    };
    const response = await page.goto(base + '#/', { waitUntil: 'networkidle' });
    await page.locator('#brandLoader').waitFor({ state: 'hidden' });
    assert(response.status() === 200, 'Homepage loads');
    assert(await page.locator('h1').count() === 1, 'Homepage has one main heading');
    assert(await page.locator('.celebrate-message').count() === 1, 'Hero has one message overlay');
    assert(await page.locator('.celebrate-together-detail').count() === 1, 'Planning section has one detail panel');
    assert(await page.locator('.marketplace-menu summary svg path').count() === 1, 'Navigation menu has a visible hamburger icon');
    assert(await page.locator('.celebrate-poster').count() === 7, 'All seven occasion cards render');
    assert(await page.locator('.marketplace-card').count() === 4, 'Homepage shows four recommended vendors');
    await assets();
    assert(await page.locator('img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0)), 'Every local image loads');

    for (const width of [320, 360, 390, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: width < 600 ? 844 : 1000 });
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `No page overflow at ${width}px`);
      assert(await page.locator('#homeTitle').evaluate(el => el.scrollWidth <= el.clientWidth + 1), `Hero headline fits at ${width}px`);
      const nav = await page.locator('.header-inner').boundingBox();
      assert(nav.x >= 0 && nav.x + nav.width <= width + 1, `Floating navigation fits at ${width}px`);
      assert(await page.locator('.celebrate-hero').evaluate(el => getComputedStyle(el).backgroundColor) === 'rgb(142, 4, 19)', `Burgundy hero appears at ${width}px`);
    }
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: path.join(output, 'desktop-opening.png') });
    await page.screenshot({ path: path.join(output, 'desktop-home.png'), fullPage: true });
    await scan('Desktop homepage');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'mobile-opening.png') });
    await page.screenshot({ path: path.join(output, 'mobile-home.png'), fullPage: true });
    await scan('Mobile homepage');
    await page.locator('.marketplace-menu summary').focus();
    await page.keyboard.press('Enter');
    assert(await page.locator('.marketplace-menu').evaluate(el => el.open), 'Mobile menu opens from the keyboard');
    await page.keyboard.press('Escape');
    assert(!await page.locator('.marketplace-menu').evaluate(el => el.open), 'Escape closes the mobile menu');
    assert(await page.locator('.marketplace-menu summary').evaluate(el => el === document.activeElement), 'Escape restores focus to the menu control');
    await page.setViewportSize({ width: 1440, height: 1000 });

    await page.locator('.celebrate-desktop-nav [data-home-scroll="homeHow"]').click();
    assert(await page.locator('#homeHow').evaluate(el => { const r = el.getBoundingClientRect(); return r.top >= 100 && r.top < 200; }), 'How it works navigation scrolls below the floating header');
    await page.locator('.celebrate-nav-create').click();
    await page.locator('#eventForm').waitFor();
    assert(await page.locator('body').evaluate(el => !el.classList.contains('is-marketplace-home')), 'Homepage styling leaves the event form');
    assert(await page.locator('body').evaluate(el => getComputedStyle(el).getPropertyValue('--brand-ink').trim()) === '#8e0413', 'Inner pages retain Vendeze burgundy');
    await home();
    await page.locator('[data-home-occasion="Birthday"]').click();
    await page.locator('#eventForm').waitFor();
    assert(await page.locator('[data-type="Birthday"]').getAttribute('aria-checked') === 'true', 'Birthday poster preselects birthday in the event form');
    await page.locator('#f-name').fill('A good birthday');
    await page.locator('#f-date').fill('2027-02-14');
    await page.locator('#f-time').fill('18:00');
    await page.locator('#f-guests').fill('100');
    await page.locator('#f-location').fill('Kallady');
    await page.locator('#continueBtn').click();
    await page.waitForURL('**#/services');
    await home();
    assert(await page.locator('.celebrate-current-event').isVisible(), 'Created event appears on the homepage');
    assert((await page.locator('.celebrate-current-event').innerText()).includes('A good birthday'), 'Homepage plan shows the saved event name');
    await page.locator('.celebrate-hero [data-action="create-event"]').click();
    await page.locator('#eventForm').waitFor();
    assert(await page.locator('#f-name').inputValue() === 'A good birthday', 'Continue event opens existing details');
    await home();

    await page.locator('[data-home-category="photo"]').click();
    assert(await page.locator('.marketplace-card').count() === 3, 'Photography filter updates homepage vendors');
    assert(await page.locator('[data-home-category="photo"]').getAttribute('aria-pressed') === 'true', 'Selected service has an accessible pressed state');
    await page.locator('#homeSearchInput').fill('Lens');
    await page.locator('#homeSearchArea').selectOption('Kallady');
    await page.locator('#homeSearchForm [type="submit"]').click();
    await page.locator('#searchResults').waitFor();
    assert(await page.locator('#searchInput').inputValue() === 'Lens', 'Homepage search carries its query to results');
    assert(await page.locator('#fArea').inputValue() === 'Kallady', 'Homepage search carries its area to results');
    assert(await page.locator('#searchResults .vendor-card').count() === 1, 'Combined query, service, and area return the correct vendor');
    await page.locator('.vendor-photo-link').first().click();
    await page.locator('.detail-hero').waitFor();
    assert(await page.locator('.detail-hero img').evaluate(img => img.complete && img.naturalWidth > 0), 'Shared vendor photo works on the detail page');
    await home();
    await page.locator('[data-home-category=""]').click();
    await page.locator('.marketplace-save').first().click();
    assert(await page.locator('.marketplace-save').first().getAttribute('aria-pressed') === 'true', 'Save heart updates without leaving the homepage');
    await page.reload({ waitUntil: 'networkidle' });
    await page.locator('#brandLoader').waitFor({ state: 'hidden' });
    assert(await page.locator('.marketplace-save').first().getAttribute('aria-pressed') === 'true', 'Saved vendor persists after refresh');
    await page.locator('.marketplace-menu summary').click();
    await page.locator('.marketplace-menu [data-action="saved"]').click();
    await page.waitForURL('**#/saved');
    assert(await page.locator('.vendor-card').count() === 1, 'Saved list contains the selected vendor');
    await home();
    await page.locator('.celebrate-nav-login').click();
    await page.locator('#signInForm').waitFor();
    assert(await page.locator('body').evaluate(el => !el.classList.contains('is-marketplace-home')), 'Homepage presentation is removed on the sign-in screen');
    assert(await page.locator('#signInForm').isVisible(), 'Account navigation opens sign-in');
    await home();
    await page.locator('.poster-wedding').click();
    await page.locator('#eventForm').waitFor();
    assert(await page.locator('#typeChips [aria-checked="true"]').innerText() === 'Birthday', 'Choosing another poster preserves an existing event type while editing');
    await home();
    assert(await page.evaluate(() => localStorage.getItem('vendeze-state-v2')) === 'production-storage-untouched', 'Preview activity leaves production storage untouched');
    await home();
    await page.locator('[data-home-all-vendors]').click();
    await page.locator('#searchResults').waitFor();
    assert(await page.locator('#searchResults .vendor-card').count() === 16, 'Explore all vendors opens the full marketplace');
    await home();
    await page.setViewportSize({ width: 390, height: 844 });
    await assets();
    await page.screenshot({ path: path.join(output, 'mobile-with-event-opening.png') });
    await page.screenshot({ path: path.join(output, 'mobile-with-event.png'), fullPage: true });
    await page.locator('.marketplace-menu summary').click();
    assert(await page.locator('.marketplace-menu nav').isVisible(), 'Mobile menu opens');
    await scan('Mobile homepage with open menu');
    await page.keyboard.press('Escape');
    assert(await page.locator('.marketplace-menu').getAttribute('open') === null, 'Escape closes the menu');
    assert(await page.locator('.marketplace-menu summary').evaluate(el => el === document.activeElement), 'Escape returns keyboard focus to the menu control');
    await page.locator('.marketplace-menu summary').click();
    await page.locator('.marketplace-menu [data-home-scroll="homeBusiness"]').click();
    assert(await page.locator('.marketplace-menu').getAttribute('open') === null, 'Mobile in-page navigation closes the menu');
    assert(await page.locator('#homeBusiness').evaluate(el => el.getBoundingClientRect().top >= 90 && el.getBoundingClientRect().top < 180), 'Business section scrolls clear of the mobile header');
    await page.locator('#homeBusiness [data-home-account]').click();
    await page.locator('#signInForm').waitFor();
    assert(await page.locator('#signInForm').isVisible(), 'Business join action opens the existing account flow');
    await home();
    assert(await page.evaluate(() => localStorage.getItem('vendeze-state-v2')) === 'production-storage-untouched', 'Preview leaves production storage untouched');
    assert(!errors.length, 'No browser runtime errors');
    assert(!failedAssets.length, 'No failed local assets');
    assert(!apiRequests.length, 'Preview sends no backend requests');

    const motionPage = await context.newPage();
    await motionPage.emulateMedia({ reducedMotion: 'no-preference' });
    await motionPage.goto(base + '#/', { waitUntil: 'networkidle' });
    await motionPage.locator('#brandLoader').waitFor({ state: 'hidden' });
    assert(await motionPage.locator('.celebrate-hero-copy').evaluate(el => getComputedStyle(el).animationName) === 'celebrate-arrive', 'Hero animates after the loading introduction');
    await motionPage.locator('#homeHow .celebrate-section-heading').scrollIntoViewIfNeeded();
    await motionPage.waitForFunction(() => Number(getComputedStyle(document.querySelector('#homeHow .celebrate-section-heading')).opacity) === 1);
    assert(await motionPage.locator('#homeHow .celebrate-section-heading').evaluate(el => Number(getComputedStyle(el).opacity) === 1), 'Section headings remain visible with motion enabled');
    assert(await motionPage.locator('.celebrate-hero-sticker').evaluate(el => getComputedStyle(el).animationName) === 'celebrate-float', 'Celebration sticker has gentle motion');
    const nav = motionPage.locator('.header-inner');
    const scroll = async y => {
      await motionPage.evaluate(y => scrollTo({ top: y, behavior: 'instant' }), y);
      await motionPage.waitForTimeout(350);
    };
    const navVisible = () => nav.evaluate(el => el.getBoundingClientRect().top >= 0);
    const navHidden = () => nav.evaluate(el => el.getBoundingClientRect().bottom < 0);
    await scroll(0);
    assert(await navVisible(), 'Navbar starts visible at the top');
    assert(await nav.evaluate(el => getComputedStyle(el).transitionDuration) === '0.28s', 'Navbar uses the reference 280ms slide timing');
    await scroll(700);
    assert(await navHidden(), 'Desktop navbar slides completely out of view when scrolling down');
    await motionPage.screenshot({ path: path.join(output, 'navbar-hidden-desktop.png') });
    await scroll(650);
    assert(await navVisible(), 'Desktop navbar slides back when scrolling up');
    await motionPage.screenshot({ path: path.join(output, 'navbar-revealed-desktop.png') });
    await scroll(654);
    assert(await navVisible(), 'Tiny downward movements do not flicker the navbar');
    await scroll(800);
    assert(await navHidden(), 'Continuing downward hides the navbar again');
    await motionPage.locator('.marketplace-menu summary').focus();
    await motionPage.waitForTimeout(350);
    assert(await navVisible(), 'Keyboard focus reveals the hidden navigation');
    await scroll(1100);
    assert(await navVisible(), 'Focused navigation stays visible during scrolling');
    await motionPage.keyboard.press('Enter');
    assert(await motionPage.locator('.marketplace-menu').evaluate(el => el.open), 'Keyboard opens the pinned menu');
    await motionPage.locator('#app').evaluate(el => el.focus({ preventScroll: true }));
    await scroll(1400);
    assert(await navVisible(), 'An open menu keeps the navbar visible even after focus leaves it');
    await motionPage.locator('.marketplace-menu summary').focus();
    await motionPage.locator('.marketplace-menu summary').focus();
    await motionPage.keyboard.press('Escape');
    assert(!await motionPage.locator('.marketplace-menu').evaluate(el => el.open), 'Escape closes the pinned menu');
    await motionPage.locator('#app').evaluate(el => el.focus({ preventScroll: true }));
    await scroll(1600);
    assert(await navHidden(), 'Normal hiding resumes after the menu closes and focus leaves');
    await motionPage.emulateMedia({ reducedMotion: 'reduce' });
    await motionPage.waitForTimeout(100);
    assert(await navVisible(), 'Turning on reduced motion reveals the navbar');
    await scroll(1900);
    assert(await navVisible(), 'Reduced-motion users keep a stable visible navbar');
    await motionPage.emulateMedia({ reducedMotion: 'no-preference' });
    await motionPage.setViewportSize({ width: 390, height: 844 });
    await scroll(0);
    assert(await navVisible(), 'Mobile navbar starts visible');
    await scroll(650);
    assert(await navHidden(), 'Mobile navbar slides completely out of view when scrolling down');
    await motionPage.screenshot({ path: path.join(output, 'navbar-hidden-mobile.png') });
    await scroll(600);
    assert(await navVisible(), 'Mobile navbar returns when scrolling up');
    await motionPage.screenshot({ path: path.join(output, 'navbar-revealed-mobile.png') });
    await scroll(700);
    await motionPage.evaluate(() => { location.hash = '#/search'; });
    await motionPage.locator('#searchResults').waitFor();
    await motionPage.waitForFunction(() => document.querySelector('.header-inner').getBoundingClientRect().top >= 0);
    assert(await navVisible(), 'Navigating away restores the normal page header');
    await scroll(1000);
    assert(await navHidden(), 'Shared scroll animation also works on inner-page navigation');
    await motionPage.evaluate(() => { location.hash = '#/'; });
    await motionPage.locator('.celebrate-home').waitFor();
    await motionPage.locator('#app').evaluate(el => el.focus({ preventScroll: true }));
    await scroll(0);
    await scroll(700);
    assert(await navHidden(), 'Scroll animation works after returning to the homepage');
    await scroll(0);
    assert(await navVisible(), 'Returning to the top always reveals the navbar');
    await motionPage.close();
    fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify({ passed: true, checks: checks.length, details: checks, accessibility, errors, failedAssets, apiRequests }, null, 2));
    console.log(JSON.stringify({ passed: true, checks: checks.length, accessibilityScans: accessibility.length }));
  } catch (e) {
    fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify({ passed: false, error: e.message, checks: checks.length, details: checks, accessibility, errors, failedAssets, apiRequests }, null, 2));
    throw e;
  } finally { await browser.close(); }
}
main().catch(e => { console.error(e.stack); process.exitCode = 1; });
